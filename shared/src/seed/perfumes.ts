import type { Accord, Gender, Occasion, Perfume, Season } from '../types';
import { fragranticaSearchUrl } from '../types';
import { normalizeNotes } from '../normalize';
import { fillHeuristics } from '../heuristics';

interface SeedInput {
  id: string;
  name: string;
  brand: string;
  year: number;
  gender: Gender;
  family: string;
  accords: [string, number][];
  top: string[];
  heart: string[];
  base: string[];
  seasons?: Season[];
  occasions?: Occasion[];
  rating: number;
  votes: number;
  url?: string;
}

function p(s: SeedInput): Perfume {
  const accords: Accord[] = s.accords.map(([name, weight]) => ({ name, weight }));
  return fillHeuristics({
    id: s.id,
    name: s.name,
    brand: s.brand,
    year: s.year,
    gender: s.gender,
    family: s.family,
    accords,
    notesTop: normalizeNotes(s.top),
    notesHeart: normalizeNotes(s.heart),
    notesBase: normalizeNotes(s.base),
    seasons: s.seasons ?? [],
    occasions: s.occasions ?? [],
    rating: s.rating,
    votes: s.votes,
    description: null,
    fragranticaUrl: s.url ?? fragranticaSearchUrl(s.brand, s.name),
  });
}

